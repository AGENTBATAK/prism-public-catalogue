const { chromium } = require('@playwright/test');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ channel: process.env.PRISM_BROWSER_CHANNEL || 'chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; const apiCalls = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', req => { if (req.url().includes('/api/')) apiCalls.push(req.url()); });
  const origin = process.argv[2] || 'http://127.0.0.1:8100/';
  await page.goto(origin + '#/library');
  await page.locator('.library-card').first().waitFor();
  await page.locator('.skip-link').focus();
  await page.keyboard.press('Enter');
  assert.equal(new URL(page.url()).hash, '#/library');
  assert.equal(await page.locator('.library-card').count(), 24);
  assert.equal(await page.locator('.library-count span').innerText(), '787');
  assert.equal(await page.locator('.header-signin').count(), 0);
  assert.equal(await page.locator('.post-button,.post-link').count(), 0);
  assert.equal(await page.getByText('Generic cover · not a page preview', { exact: true }).count(), 24);
  await page.locator('.library-search input').fill('123456789/1260');
  await page.locator('.library-search button').click();
  await page.waitForFunction(() => document.querySelector('.library-count span')?.textContent === '1');
  assert.equal(await page.locator('.library-card').count(), 1);
  assert.equal(await page.getByRole('link', { name: 'Open PDF on NCPOR', exact: true }).getAttribute('href'), 'http://14.139.119.23:8080/dspace/bitstream/123456789/1260/1/5.30ISEA-First_Expedition_to_SouthPole_Report.pdf');
  assert.equal(await page.getByRole('link', { name: 'View NCPOR source page', exact: true }).getAttribute('href'), 'http://14.139.119.23:8080/dspace/handle/123456789/1260');
  await page.getByRole('button', { name: 'Research table' }).click();
  await page.locator('.library-table tbody tr').first().waitFor();
  assert.equal(await page.locator('.library-table tbody tr').count(), 1);
  await page.reload();
  await page.locator('.library-table tbody tr').first().waitFor();
  await page.goto(origin + '#/library');
  await page.locator('.library-count span').filter({ hasText: '787' }).waitFor();
  await page.getByRole('button', { name: 'Next', exact: true }).click();
  await page.waitForFunction(() => location.hash.includes('page=2'));
  await page.goto(origin + '#/stations');
  await page.locator('.station-card').first().waitFor();
  assert.equal(await page.locator('.station-card').count(), 3);
  await page.goto(origin + '#/gallery');
  await page.locator('.gallery-tile button').first().click();
  await page.getByRole('dialog').waitFor();
  await page.locator('.gallery-lightbox img').evaluate(img => img.decode());
  assert.equal(await page.locator('.gallery-lightbox img').evaluate(img => img.complete && img.naturalWidth > 0), true);
  await page.keyboard.press('Escape');
  await page.goto(origin + '#/learn');
  await page.locator('.learn-grid').waitFor();
  await page.goto(origin + '#/ask');
  await page.locator('.chat-composer').waitFor();
  assert.equal(await page.locator('.chat-attach-button').count(), 0);
  assert.equal(await page.getByText('PRISM assistant', { exact: true }).count(), 1);
  await page.goto(origin + '#/library');
  await page.locator('.library-count span').filter({ hasText: '787' }).waitFor();
  await page.getByRole('button', { name: 'Thumbnails', exact: true }).click();
  await page.getByRole('combobox', { name: 'Language', exact: true }).selectOption('hi');
  await page.getByText('सामान्य कवर · PDF पृष्ठ का पूर्वावलोकन नहीं', { exact: true }).first().waitFor();
  await page.getByRole('combobox').filter({ has: page.locator('option[value="en"]') }).selectOption('en');
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2), true);
  const broken = await page.locator('img').evaluateAll(imgs => imgs.filter(img => img.complete && !img.naturalWidth).map(img => img.src));
  assert.deepEqual(broken, []);
  assert.deepEqual(apiCalls, []);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ reports: 787, browserChecks: 'cards, table, PDF/source URLs, search, pagination, reload, stations, gallery, learning, disabled features, Hindi, mobile', backendRequests: apiCalls.length, pageErrors: errors.length }));
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
